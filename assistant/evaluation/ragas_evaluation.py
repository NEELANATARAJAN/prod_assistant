import asyncio
from utils.model_loader import ModelLoader
from ragas import SingleTurnSample
from ragas.llms import LangchainLLMWrapper
from ragas.embeddings import LangchainEmbeddingsWrapper
from ragas.metrics import LLMContextPrecisionWithoutReference, ResponseRelevancy
import asyncio
import grpc.experimental.aio as grpc_aio
grpc_aio.init_grpc_aio()
model_loader=ModelLoader()

def evaluate_context_precision(query, response, retrieved_context):
    """
    Evaluate the precision of the retrieved context - Are the docs actually useful?
    """
    try:
        sample=SingleTurnSample(
            user_input=query,
            response=response,
            retrieved_contexts=retrieved_context
        )
        async def main():
            llm=model_loader.load_evaluator_llm()
            evaluator_llm=LangchainLLMWrapper(llm)
            context_precision=LLMContextPrecisionWithoutReference(llm=evaluator_llm)
            result = await context_precision.evaluate(sample)
            return result

        return asyncio.run(main())
    except Exception as e:
        print(f"Error evaluating context precision: {e}")
        return e

def evaluate_response_relevancy(query, response, retrieved_context):
    """
    Evaluate the relevancy of the answer. Does the answer actually address the question?
    Args:
        query (str): Question raised by the user
        response (str): Response generated by the model
        retrieved_context (list): List of retrieved documents
    """
    try:
        sample = SingleTurnSample(
            user_input=query,
            response=response,
            retrieved_contexts=retrieved_context
        )

        async def main():
            llm = model_loader.load_evaluator_llm()
            embedding_model = model_loader.load_evaluator_embeddings()
            evaluator_llm = LangchainLLMWrapper(llm)
            evaluator_embeddings = LangchainEmbeddingsWrapper(embedding_model)
            scorer = ResponseRelevancy(llm=evaluator_llm, embedding_model=evaluator_embeddings)
            result = await scorer.evaluate(sample)
            return result
        
        return asyncio.run(main())
    except Exception as e:
        print(f"Error evaluating response relevancy: {e}")
        return e
    